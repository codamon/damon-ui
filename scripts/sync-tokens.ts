/**
 * Write registry/damon/theme/tokens.ts into registry.json (item cssVars) and
 * app/tokens.css (docs site). Run by `pnpm registry:build`; never edit the
 * outputs by hand. tests/lib/tokens.test.ts fails if registry.json drifts.
 */
import { readFileSync, writeFileSync } from "node:fs"

import { docsBase, itemTokens, presets, type TokenMap, type TokenSet } from "../registry/damon/theme/tokens"

const block = (selector: string, vars: TokenMap) =>
  Object.keys(vars).length
    ? `${selector} {\n${Object.entries(vars)
        .map(([k, v]) => `  --${k}: ${v};`)
        .join("\n")}\n}\n`
    : ""

export function toCssVars(set: TokenSet) {
  return {
    ...(set.theme && Object.keys(set.theme).length ? { theme: set.theme } : {}),
    light: set.light,
    dark: set.dark,
  }
}

export function docsCss(): string {
  return [
    "/* Generated by scripts/sync-tokens.ts from registry/damon/theme/tokens.ts. Do not edit. */\n",
    block("@theme inline", docsBase.theme ?? {}),
    block(":root", docsBase.light),
    block(".dark", docsBase.dark),
    ...Object.entries(presets).flatMap(([name, set]) => [
      block(`[data-theme="${name}"]`, set.light),
      block(`.dark [data-theme="${name}"]`, { ...set.light, ...set.dark }),
    ]),
  ].join("\n")
}

function main() {
  const registry = JSON.parse(readFileSync("registry.json", "utf8"))
  for (const item of registry.items) {
    const set = itemTokens[item.name]
    if (set) item.cssVars = toCssVars(set)
  }
  writeFileSync("registry.json", `${JSON.stringify(registry, null, 2)}\n`)
  writeFileSync("app/tokens.css", docsCss())
  console.log(`sync-tokens: ${Object.keys(itemTokens).length} item token sets, app/tokens.css`)
}

if (import.meta.url === `file://${process.argv[1]}`) main()
